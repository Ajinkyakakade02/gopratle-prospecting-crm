-- Google Calendar Integration Migration
-- Adds tables for OAuth connections, CSRF state management, and Calendar event tracking on tasks

-- 1. Create table for storing encrypted Google Calendar OAuth connections
create table if not exists public.google_calendar_connections (
    id bigint generated by default as identity primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    sales_id bigint not null references public.sales(id) on delete cascade,
    calendar_email text,
    encrypted_access_token text not null,
    encrypted_refresh_token text not null,
    token_expires_at timestamp with time zone,
    created_at timestamp with time zone not null default now(),
    updated_at timestamp with time zone not null default now(),
    constraint uq_google_calendar_connections_user unique (user_id),
    constraint uq_google_calendar_connections_sales unique (sales_id)
);

-- Indexes for user and sales lookups
create index if not exists idx_google_calendar_connections_user_id on public.google_calendar_connections(user_id);
create index if not exists idx_google_calendar_connections_sales_id on public.google_calendar_connections(sales_id);

-- Enable RLS
alter table public.google_calendar_connections enable row level security;

-- RLS Policies: users can only manage their own connection
create policy "Users can view their own calendar connection"
    on public.google_calendar_connections
    for select
    to authenticated
    using (auth.uid() = user_id);

create policy "Users can insert their own calendar connection"
    on public.google_calendar_connections
    for insert
    to authenticated
    with check (auth.uid() = user_id);

create policy "Users can update their own calendar connection"
    on public.google_calendar_connections
    for update
    to authenticated
    using (auth.uid() = user_id);

create policy "Users can delete their own calendar connection"
    on public.google_calendar_connections
    for delete
    to authenticated
    using (auth.uid() = user_id);

-- Explicit grants
grant all on public.google_calendar_connections to authenticated, service_role;

-- 2. Create table for OAuth state validation (CSRF protection)
create table if not exists public.google_calendar_oauth_states (
    state text primary key,
    user_id uuid not null references auth.users(id) on delete cascade,
    sales_id bigint not null references public.sales(id) on delete cascade,
    return_url text,
    created_at timestamp with time zone not null default now(),
    expires_at timestamp with time zone not null default (now() + interval '10 minutes')
);

create index if not exists idx_google_calendar_oauth_states_user_id on public.google_calendar_oauth_states(user_id);

-- Enable RLS
alter table public.google_calendar_oauth_states enable row level security;

create policy "Users can manage their own oauth states"
    on public.google_calendar_oauth_states
    for all
    to authenticated
    using (auth.uid() = user_id)
    with check (auth.uid() = user_id);

grant all on public.google_calendar_oauth_states to authenticated, service_role;

-- 3. Add Google Calendar event tracking columns to tasks table
alter table public.tasks add column if not exists google_event_id text;
alter table public.tasks add column if not exists google_event_link text;
alter table public.tasks add column if not exists google_event_status text default 'unsynced' check (google_event_status in ('unsynced', 'synced', 'failed'));
alter table public.tasks add column if not exists google_event_error text;

create index if not exists idx_tasks_google_event_id on public.tasks(google_event_id) where google_event_id is not null;
